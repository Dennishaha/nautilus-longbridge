from __future__ import annotations

import asyncio
from collections.abc import Callable
from typing import Any, Protocol

from .config import LongbridgeSafeSettings, build_sdk_config


class QuoteContext(Protocol):
    def set_on_quote(self, callback: Callable[..., Any]) -> None: ...
    def set_on_depth(self, callback: Callable[..., Any]) -> None: ...
    def set_on_trades(self, callback: Callable[..., Any]) -> None: ...
    def set_on_candlestick(self, callback: Callable[..., Any]) -> None: ...
    async def subscribe(self, symbols: list[str], sub_types: list[Any]) -> Any: ...
    async def unsubscribe(self, symbols: list[str], sub_types: list[Any]) -> Any: ...
    async def subscribe_candlesticks(
        self, symbol: str, period: Any, trade_sessions: Any = Any
    ) -> Any: ...
    async def unsubscribe_candlesticks(self, symbol: str, period: Any) -> Any: ...
    async def quote(self, symbols: list[str]) -> list[Any]: ...
    async def trades(self, symbol: str, count: int) -> list[Any]: ...
    async def candlesticks(
        self, symbol: str, period: Any, count: int, adjust_type: Any, trade_sessions: Any = Any
    ) -> list[Any]: ...
    async def history_candlesticks_by_date(
        self, symbol: str, period: Any, adjust_type: Any, **kwargs: Any
    ) -> list[Any]: ...
    async def depth(self, symbol: str) -> Any: ...
    async def static_info(self, symbols: list[str]) -> list[Any]: ...
    async def subscriptions(self) -> list[Any]: ...


class TradeContext(Protocol):
    def set_on_order_changed(self, callback: Callable[..., Any]) -> None: ...
    async def subscribe(self, topics: list[Any]) -> Any: ...
    async def unsubscribe(self, topics: list[Any]) -> Any: ...
    async def today_orders(self, **kwargs: Any) -> list[Any]: ...
    async def today_executions(self, **kwargs: Any) -> list[Any]: ...
    async def order_detail(self, order_id: str, is_attached: bool = False) -> Any: ...
    async def submit_order(self, **kwargs: Any) -> Any: ...
    async def replace_order(self, **kwargs: Any) -> Any: ...
    async def cancel_order(self, order_id: str, is_attached: bool = False) -> Any: ...
    async def account_balance(self, currency: str | None = None) -> list[Any]: ...
    async def estimate_max_purchase_quantity(self, **kwargs: Any) -> Any: ...
    async def stock_positions(self, symbols: list[str] | None = None) -> Any: ...


class ContextFactory(Protocol):
    def quote(self, settings: LongbridgeSafeSettings, loop: asyncio.AbstractEventLoop) -> Any: ...
    def trade(self, settings: LongbridgeSafeSettings, loop: asyncio.AbstractEventLoop) -> Any: ...


class LongbridgeContextFactory:
    """Creates official SDK contexts only when a client connects."""

    def quote(self, settings: LongbridgeSafeSettings, loop: asyncio.AbstractEventLoop) -> Any:
        from longbridge.openapi import AsyncQuoteContext

        return AsyncQuoteContext.create(build_sdk_config(settings), loop_=loop)

    def trade(self, settings: LongbridgeSafeSettings, loop: asyncio.AbstractEventLoop) -> Any:
        from longbridge.openapi import AsyncTradeContext

        return AsyncTradeContext.create(build_sdk_config(settings), loop_=loop)
